// Converts the WHO LMS text tables in data/who into src/who/tables.ts.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')

function load(file) {
  const rows = readFileSync(join(root, 'data/who', file), 'utf8')
    .trim()
    .split('\n')
    .slice(1)
  const bySex = { 1: [], 2: [] }
  let start = null
  for (const row of rows) {
    const [sex, key, l, m, s] = row.split('\t')
    if (start === null) start = Number(key)
    bySex[sex].push(Number(l), Number(m), Number(s))
  }
  return { start, male: bySex[1], female: bySex[2] }
}

const tables = {
  lengthForAge: { ...load('lenanthro.txt'), step: 1 },
  weightForAge: { ...load('weianthro.txt'), step: 1 },
  weightForLength: { ...load('wflanthro.txt'), step: 0.1 },
  weightForHeight: { ...load('wfhanthro.txt'), step: 0.1 },
}

let out = '// Generated by scripts/build-who-tables.mjs from data/who. Do not edit.\n'
out += "import type { LmsTable } from './types'\n\n"
for (const [name, t] of Object.entries(tables)) {
  out += `export const ${name}: LmsTable = {\n  start: ${t.start},\n  step: ${t.step},\n`
  out += `  male: [${t.male.join(',')}],\n  female: [${t.female.join(',')}],\n}\n\n`
}
mkdirSync(join(root, 'src/who'), { recursive: true })
writeFileSync(join(root, 'src/who/tables.ts'), out)
console.log('wrote src/who/tables.ts')
